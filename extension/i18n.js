function pickLang(saved) {
  if (CONFIG.LANGS.includes(saved)) return saved;
  // 처음에는 브라우저 언어 (한국어 브라우저는 영어로 시작, 서랍에서 바꿀 수 있음)
  const nav = (navigator.language || 'en').slice(0, 2);
  return CONFIG.LANGS.includes(nav) && nav !== 'ko' ? nav : 'en';
}
